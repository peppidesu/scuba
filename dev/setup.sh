#!/usr/bin/env bash
# One-time bootstrap for the local dev stack (see dev/README.md).
#
# - waits for authentik and NetBird to come up
# - creates the NetBird owner user and a 365-day API token (needs NB_SETUP_PAT_ENABLED, set in compose.yaml)
# - writes dev/scuba.env with everything scuba needs
#
# Safe to re-run: does nothing if dev/scuba.env already holds a token.
set -euo pipefail
cd "$(dirname "$0")"

NETBIRD_URL=${NETBIRD_URL:-http://localhost:8080}
AUTHENTIK_URL=${AUTHENTIK_URL:-http://localhost:9000}
SCUBA_URL=${SCUBA_URL:-http://localhost:3000}
OWNER_EMAIL=${OWNER_EMAIL:-admin@example.com}   # same email as the authentik admin, so scuba can link the two
OWNER_NAME=${OWNER_NAME:-Admin}
OWNER_PASSWORD=${OWNER_PASSWORD:-admin-password}
CLIENT_SECRET=${SCUBA_OIDC_CLIENT_SECRET:-scuba-dev-client-secret}
ENV_FILE=scuba.env

wait_for() { # url, description
  local tries=0
  until curl -fsS -o /dev/null "$1" 2>/dev/null; do
    tries=$((tries + 1))
    if [ "$tries" -gt 90 ]; then
      echo "timed out waiting for $2 ($1) — try: docker compose -f dev/compose.yaml logs" >&2
      exit 1
    fi
    sleep 2
  done
  echo "ok: $2"
}

# A fresh NetBird ships a "Default" policy that allows ALL traffic between ALL peers. scuba's model is
# deny-by-default (only `All -> reef` is open), so drop it, or access control would silently not work.
drop_default_policy() { # token
  local id
  id=$(curl -fsS -H "Authorization: Token $1" "$NETBIRD_URL/api/policies" \
        | grep -o '"id":"[^"]*","name":"Default"' | head -1 | sed 's/"id":"\([^"]*\)".*/\1/')
  if [ -n "$id" ]; then
    curl -fsS -X DELETE -H "Authorization: Token $1" "$NETBIRD_URL/api/policies/$id" >/dev/null
    echo "removed NetBird's allow-all 'Default' policy"
  fi
}

write_env() { # token
  cat > "$ENV_FILE" <<ENV
# Generated by dev/setup.sh — dev only. Load with:  set -a; . dev/scuba.env; set +a
SCUBA_LISTEN=127.0.0.1:3000
SCUBA_PUBLIC_URL=$SCUBA_URL
DATABASE_URL=sqlite://dev/scuba.db
OIDC_ISSUER_URL=$AUTHENTIK_URL/application/o/scuba/
OIDC_CLIENT_ID=scuba
OIDC_CLIENT_SECRET=$CLIENT_SECRET
NETBIRD_API_URL=$NETBIRD_URL
NETBIRD_API_TOKEN=$1
ENV
  echo "wrote dev/$ENV_FILE"
}

if [ -f "$ENV_FILE" ] && grep -q '^NETBIRD_API_TOKEN=.\+' "$ENV_FILE"; then
  echo "dev/$ENV_FILE already has an API token; nothing to do (delete it to start over)"
  exit 0
fi

wait_for "$AUTHENTIK_URL/-/health/ready/" "authentik"
# the scuba OIDC app comes from a blueprint the worker applies a little after startup
wait_for "$AUTHENTIK_URL/application/o/scuba/.well-known/openid-configuration" "authentik: scuba OIDC application"
wait_for "$NETBIRD_URL/api/instance" "netbird"

resp=$(curl -sS -w '\n%{http_code}' -X POST "$NETBIRD_URL/api/setup" \
  -H 'Content-Type: application/json' \
  -d "{\"email\":\"$OWNER_EMAIL\",\"name\":\"$OWNER_NAME\",\"password\":\"$OWNER_PASSWORD\",\"create_pat\":true,\"pat_expire_in\":365}")
status=${resp##*$'\n'}
body=${resp%$'\n'*}

if [ "$status" = "200" ] || [ "$status" = "201" ]; then
  token=$(printf '%s' "$body" | sed -n 's/.*"personal_access_token" *: *"\([^"]*\)".*/\1/p')
  if [ -z "$token" ]; then
    echo "NetBird created the owner but returned no token (is NB_SETUP_PAT_ENABLED set on netbird-server?)" >&2
    exit 1
  fi
  write_env "$token"
  drop_default_policy "$token"
  echo
  echo "NetBird dashboard: $NETBIRD_URL      login: $OWNER_EMAIL / $OWNER_PASSWORD"
  echo "authentik admin:   $AUTHENTIK_URL    login: akadmin / admin   (also alice / dev, bob / dev)"
else
  echo "NetBird setup failed (HTTP $status): $body" >&2
  echo "If the owner already exists, create an API token in the dashboard (Team > Service Users)" >&2
  echo "and put it in dev/$ENV_FILE as NETBIRD_API_TOKEN, or run 'docker compose -f dev/compose.yaml down -v' to reset." >&2
  exit 1
fi
